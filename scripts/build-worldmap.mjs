// Builds js/worldmap-data.js: a dot grid of the world's land for the ATLAS map.
// Run once (output is committed):
//   mkdir /tmp/wm && cd /tmp/wm && npm i world-atlas@2 d3-geo@3 topojson-client@3
//   node scripts/build-worldmap.mjs /tmp/wm
import { createRequire } from 'node:module';
import { writeFile } from 'node:fs/promises';
import { pathToFileURL } from 'node:url';

const deps = process.argv[2] || process.cwd();
const require = createRequire(deps + '/package.json');
const land = require('world-atlas/land-110m.json');
const { feature } = require('topojson-client');
const { geoContains } = await import(pathToFileURL(require.resolve('d3-geo')).href);

const STEP = 2, LAT_MAX = 80, LAT_MIN = -58;
const shape = feature(land, land.objects.land);
const cols = 360 / STEP, rows = [];
for (let lat = LAT_MAX; lat >= LAT_MIN; lat -= STEP) {
  let bits = '';
  for (let c = 0; c < cols; c++) bits += geoContains(shape, [-180 + STEP / 2 + c * STEP, lat]) ? '1' : '0';
  let hex = '';
  for (let i = 0; i < bits.length; i += 4) hex += parseInt(bits.slice(i, i + 4).padEnd(4, '0'), 2).toString(16);
  rows.push(hex);
}
const out = `/* Generated by scripts/build-worldmap.mjs — land dots on a ${STEP}° grid (Natural Earth 110m via world-atlas). */
window.WORLD = { step: ${STEP}, latMax: ${LAT_MAX}, cols: ${cols}, rows: ${JSON.stringify(rows)} };
`;
await writeFile(new URL('../js/worldmap-data.js', import.meta.url), out);
console.log('rows', rows.length, 'bytes', out.length, 'land dots', rows.join('').split('').reduce((n, h) => n + parseInt(h, 16).toString(2).split('1').length - 1, 0));
